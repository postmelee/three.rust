import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createVerifiedViewerSourceMap, decodeViewerMappings, resolveViewerSourceMapURL } from '../scripts/apps/viewer-profile-source-maps.mjs';
import { VIEWER_PIN } from '../scripts/apps/viewer-adapter.mjs';

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
function vlq(value) {
 let unsigned = Math.abs(value) * 2 + (value < 0 ? 1 : 0), result = '';
 do { let digit = unsigned % 32; unsigned = Math.floor(unsigned / 32); if (unsigned) digit += 32; result += alphabet[digit]; } while (unsigned);
 return result;
}
const segment = values => values.map(vlq).join('');
function fixture({ text = 'class Viewer { animate() { return 1; } }', generated = 'function a(){return 1;}', mappings, label = 'adapted/src/viewer.js', sourceContent, inputContent } = {}) {
 const contents = sourceContent === undefined ? text : sourceContent;
 const map = { version: 3, file: 'app.js', sources: [label], sourcesContent: [contents], names: [], mappings: mappings ?? segment([0, 0, 0, text.indexOf('animate')]) };
 const bytes = Buffer.from(generated), mapBytes = Buffer.from(JSON.stringify(map)), input = Buffer.from(inputContent ?? text);
 const prepared = { status: 'prepared', viewerPin: VIEWER_PIN, instrumentation: null, integrity: { originalSourcesAndDistUnchanged: true, capturedInputsUnchanged: true },
  outputs: [{ file: 'dist/assets/app.js', sha256: hash(bytes), bytes: bytes.length }, { file: 'dist/assets/app.js.map', sha256: hash(mapBytes), bytes: mapBytes.length }],
  buildInputs: [{ file: label, sha256: hash(input), bytes: input.length }], sources: [{ file: 'viewer/src/viewer.js', sha256: hash(input), bytes: input.length }], adaptations: [],
  sourceMaps: [{ file: 'dist/assets/app.js.map', servedSha256: hash(mapBytes), sourceCount: map.sources.length, mappingsSha256: hash(map.mappings), sourcesContentSha256: hash(JSON.stringify(map.sourcesContent)), unchangedNonPathPayloadSha256: hash(JSON.stringify({ ...map, sources: [] })), nonPathPayloadUnchanged: true }] };
 return { input: { generated: { file: 'dist/assets/app.js', bytes, sha256: hash(bytes) }, sourceMap: { file: 'dist/assets/app.js.map', bytes: mapBytes, sha256: hash(mapBytes) }, prepared }, map, generated };
}

test('exact verified generated mapping resolves the original AST function, not a minified name', () => {
 const { input } = fixture(), result = createVerifiedViewerSourceMap(input).resolve(0, 0);
 assert.equal(result.resolved, true); assert.equal(result.label, 'Viewer.animate'); assert.equal(result.source.file, 'adapted/src/viewer.js');
 assert.equal(result.source.upstream.file, 'viewer/src/viewer.js'); assert.equal(result.source.mapping.method, 'exact-generated-segment-to-verified-input-AST');
});

test('no GLB interpolation, unknown position or top-level point becomes a guessed function', () => {
 const { input } = fixture(), resolver = createVerifiedViewerSourceMap(input);
 for (const [line, column] of [[0, 1], [99, 0], [-1, 0], [0, 999]]) assert.equal(resolver.resolve(line, column).resolved, false);
 const top = fixture({ mappings: segment([0, 0, 0, 0]) }); assert.equal(createVerifiedViewerSourceMap(top.input).resolve(0, 0).resolved, false);
});

test('explicit unmapped and duplicate exact segments remain unresolved', () => {
 const absent = fixture({ mappings: 'A' }); assert.equal(createVerifiedViewerSourceMap(absent.input).resolve(0, 0).resolved, false);
 const duplicate = fixture({ mappings: segment([0, 0, 0, 15]) + ',' + segment([0, 0, 0, 0]) });
 assert.match(createVerifiedViewerSourceMap(duplicate.input).resolve(0, 0).reason, /Ambiguous/);
});

test('negative relative deltas carry across lines without 32-bit overflow', () => {
 const map = { version: 3, file: 'x.js', sources: ['adapted/a.js', 'adapted/b.js'], sourcesContent: ['abc\ndef', 'abc\ndef'], names: ['a'],
  mappings: segment([0, 1, 1, 2, 0]) + ';' + segment([0, -1, -1, -2]) };
 const result = decodeViewerMappings(map, 'a\nb'); assert.equal(result[0][0].source, 1); assert.equal(result[1][0].source, 0); assert.equal(result[1][0].originalColumn, 0);
});

test('malformed VLQ, field counts, source/name indexes and source positions fail closed', () => {
 for (const mappings of ['g', '@', 'gggggggA', 'AA', segment([0, -1, 0, 0]), segment([0, 0, 1, 0]), segment([0, 0, 0, -1]), segment([999, 0, 0, 0]), segment([0, 0, 0, 0, 0])]) {
  const f = fixture({ mappings }); assert.throws(() => createVerifiedViewerSourceMap(f.input), undefined, mappings);
 }
});

test('source-map and generated bytes must match both exact hashes and prepared outputs', () => {
 const a = fixture(); a.input.sourceMap.bytes = Buffer.from(a.input.sourceMap.bytes.toString().replace('app.js', 'bad.js'));
 assert.throws(() => createVerifiedViewerSourceMap(a.input), /hash mismatch/);
 const b = fixture(); b.input.prepared.outputs[0].sha256 = '0'.repeat(64);
 assert.throws(() => createVerifiedViewerSourceMap(b.input), /prepared output/);
 const c = fixture(); c.input.prepared.sourceMaps[0].mappingsSha256 = '0'.repeat(64);
 assert.throws(() => createVerifiedViewerSourceMap(c.input));
});

test('unverifiable sourcesContent and absent source content retain generated fallback', () => {
 const changed = fixture({ inputContent: 'class Viewer { different(){} }' });
 const resolver = createVerifiedViewerSourceMap(changed.input); assert.equal(resolver.resolve(0, 0).resolved, false); assert.match(resolver.coverage[0].reason, /build input/);
 const absent = fixture({ sourceContent: null }); assert.equal(createVerifiedViewerSourceMap(absent.input).resolve(0, 0).resolved, false);
});

test('adapted source needs the exact original-to-adapted provenance chain', () => {
 const f = fixture(), original = Buffer.from('class Viewer { animate() { return 0; } }');
 f.input.prepared.sources[0] = { file: 'viewer/src/viewer.js', sha256: hash(original), bytes: original.length };
 f.input.prepared.adaptations.push({ file: 'src/viewer.js', originalSha256: hash(original), originalBytes: original.length,
  servedSha256: f.input.prepared.buildInputs[0].sha256, servedBytes: f.input.prepared.buildInputs[0].bytes });
 assert.equal(createVerifiedViewerSourceMap(f.input).resolve(0, 0).resolved, true);
 f.input.prepared.adaptations[0].originalSha256 = '0'.repeat(64);
 assert.equal(createVerifiedViewerSourceMap(f.input).resolve(0, 0).resolved, false);
});

test('unknown virtual sources remain unresolved and source path escapes are rejected', () => {
 const virtual = fixture({ label: '<virtual>/helper' }); assert.equal(createVerifiedViewerSourceMap(virtual.input).resolve(0, 0).resolved, false);
 for (const label of ['../escape.js', '/absolute.js', 'adapted/../escape.js', 'viewer/%2e%2e/escape.js', 'viewer\\escape.js', 'https://example.test/a.js']) {
  const f = fixture({ label }); assert.throws(() => createVerifiedViewerSourceMap(f.input), /Unsafe/);
 }
});

test('indexed maps, URL roots and instrumented preparation are unsupported', () => {
 const f = fixture(); for (const change of [{ version: 2 }, { sections: [] }, { sourceRoot: 'https://example.test/' }]) assert.throws(() => decodeViewerMappings({ ...f.map, ...change }, f.generated));
 f.input.prepared.instrumentation = 'timing'; assert.throws(() => createVerifiedViewerSourceMap(f.input), /uninstrumented/);
});

test('map URL must be a same-origin declared path without traversal, encoding or credentials', () => {
 const origin = 'http://127.0.0.1:1234', generated = origin + '/assets/app.js';
 assert.equal(resolveViewerSourceMapURL('app.js.map', generated, origin).href, origin + '/assets/app.js.map');
 for (const reference of ['../outside.map', '%2e%2e/outside.map', '//127.0.0.1:1234/assets/app.js.map', 'https://example.test/a.map', 'data:application/json,{}', 'app.js.map?x', 'app.js.map#x', 'http://user:pass@127.0.0.1:1234/app.js.map']) assert.throws(() => resolveViewerSourceMapURL(reference, generated, origin));
});
